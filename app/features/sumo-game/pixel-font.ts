// Catalan accents are drawn without the diacritic at this size
const normalize = (text: string) =>
  text.toUpperCase().normalize('NFD').replace(/[̀-ͯ]/g, '').replace(/·/g, '.')

export const textWidth = (text: string, scale = 1) => normalize(text).length * 4 * scale - scale

export function drawText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string,
  scale = 1,
) {
  ctx.fillStyle = color
  let cursor = Math.round(x)
  for (const char of normalize(text)) {
    const glyph = GLYPHS[char] ?? GLYPHS['?'] ?? []
    glyph.forEach((row, gy) => {
      for (let gx = 0; gx < 3; gx++) {
        if (row[gx] === '#')
          ctx.fillRect(cursor + gx * scale, Math.round(y) + gy * scale, scale, scale)
      }
    })
    cursor += 4 * scale
  }
}

export function drawTextCentered(
  ctx: CanvasRenderingContext2D,
  text: string,
  cx: number,
  y: number,
  color: string,
  scale = 1,
) {
  drawText(ctx, text, Math.round(cx - textWidth(text, scale) / 2), y, color, scale)
}
